"""Do pinball costs of general laws satisfy Hlawka's inequality?

Every sum of segments (the costs of the explicit laws) satisfies
c(x) + c(y) + c(z) + c(x+y+z) >= c(x+y) + c(y+z) + c(z+x), because each
segment cost is |t| times a constant plus a linear term that cancels. If all
pinball costs satisfied it, it could sharpen the relaxation in the open
asymmetric regions. This script samples random finite laws, counts
violations, and verifies one violating law in exact rational arithmetic
(costs evaluated at a tau-quantile with censored_newsvendor.asymmetric.pinball_cost).
Outcomes go to results/asymmetric/hlawka.json; the summary is generated from it.
"""

import json
from fractions import Fraction as F
from pathlib import Path

import numpy as np

from censored_newsvendor.asymmetric import level_for_ratio, pinball_cost

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results/asymmetric"


def cost(values, tau):
    q = np.quantile(values, tau, method="inverted_cdf")
    u = values - q
    return float(np.mean(np.where(u > 0, tau * u, -(1 - tau) * u)))


def hlawka(c, x, y, z):
    return c(x) + c(y) + c(z) + c(x + y + z) - c(x + y) - c(y + z) - c(z + x)


def sample(kappa, laws=600, trials=40, seed=0):
    rng = np.random.default_rng(seed)
    tau = 1 / (1 + kappa)
    count, low, example = 0, np.inf, None
    for _ in range(laws):
        n, atoms = rng.integers(2, 5), rng.integers(2, 9)
        Y = rng.integers(-6, 7, size=(atoms, n))
        for _ in range(trials):
            x, y, z = rng.integers(-3, 4, size=(3, n))
            value = hlawka(lambda v: cost(Y @ v, tau), x, y, z)
            scale = sum(cost(Y @ v, tau) for v in (x, y, z)) + 1e-12
            if value < -1e-9:
                count += 1
                if value / scale < low:
                    low, example = value / scale, (Y.tolist(), x.tolist(), y.tolist(), z.tolist())
    return count, laws * trials, (None if example is None else float(low)), example


def exact(kappa, example):
    Y, x, y, z = example
    tau = level_for_ratio(F(kappa).limit_denominator(100))
    states = [tuple(F(v) for v in row) for row in Y]
    probs = [F(1, len(states))] * len(states)

    def c(v):
        return pinball_cost(states, probs, tuple(F(int(t)) for t in v), tau)

    add = lambda *vs: [sum(t) for t in zip(*vs)]
    value = c(x) + c(y) + c(z) + c(add(x, y, z)) - c(add(x, y)) - c(add(y, z)) - c(add(z, x))
    return value


def main():
    rows = []
    for kappa in (1, 1.5, 3, 10):
        count, total, low, example = sample(kappa)
        row = {"kappa": kappa, "violations": count, "tests": total, "smallest_normalized": low}
        if example is not None:
            value = exact(kappa, example)
            row.update({"example": {"atoms": example[0], "x": example[1], "y": example[2],
                                    "z": example[3]},
                        "exact_hlawka_value": str(value), "exact_violation": value < 0})
        rows.append(row)
        print(row["kappa"], count, total, low, row.get("exact_hlawka_value"))
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "hlawka.json").write_text(json.dumps({"date": "2026-11-07", "rows": rows}, indent=1) + "\n")
    saved = json.loads((OUT / "hlawka.json").read_text())["rows"]
    lines = ["# Hlawka's inequality and pinball costs", "",
             "2026-11-07. Generated by `scripts/check_hlawka.py` from [hlawka.json](hlawka.json). "
             "Random laws with 2 to 8 equally likely integer atoms in dimension 2 to 4, integer "
             "test vectors; costs at a tau-quantile with tau = 1/(1+kappa).", "",
             "| kappa | tests | violations | smallest violation / scale | worst example verified exactly |",
             "| ---: | ---: | ---: | ---: | --- |"]
    for r in saved:
        verified = (f"{r['exact_violation']} (value {r['exact_hlawka_value']})"
                    if "exact_violation" in r else "no violation found")
        smallest = "-" if r["smallest_normalized"] is None else f"{r['smallest_normalized']:.3f}"
        lines.append(f"| {r['kappa']} | {r['tests']} | {r['violations']} | {smallest} | {verified} |")
    lines += ["", "Every sum of segments satisfies the inequality, so a violation shows that the "
              "cost is not a sum of segments (nor any zonoid support function plus a linear term).", ""]
    (OUT / "hlawka.md").write_text("\n".join(lines))


if __name__ == "__main__":
    main()

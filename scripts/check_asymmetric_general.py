"""Two-block families against the certificate bound, arbitrary shares, every kappa.

For random shares at intermediate depths (1 <= k <= n-3; the last depth is
Theorem A) and a random penalty ratio, the best two-block law
max_{K, I} Psi_kappa(a(I), A_J) is built and verified in exact arithmetic
and compared with the certificate LP, which bounds every demand law. Where
they differ, the exact relaxation is evaluated at the certificate's
maximizer, and for n <= 5 an LP over kappa-segment laws looks for a better
explicit law (at that membership, then by a short local search). With
kappa = 1 the four symmetric families of Conjecture 6 are evaluated too.

Outcomes go to results/asymmetric/general_shares.json; the markdown summary
is generated from that file.
"""

import json
import random
import time
from concurrent.futures import ProcessPoolExecutor
from fractions import Fraction as F
from pathlib import Path

import numpy as np
from scipy.optimize import minimize

from censored_newsvendor.asymmetric import (asymmetric_best_block,
                                            asymmetric_zonotope_minimal_cost, verify_segments)
from censored_newsvendor.certificates import certificate_bound
from censored_newsvendor.exact_envelopes import best_general_construction
from censored_newsvendor.seminorm_envelope import minimal_cost

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results/asymmetric"
KAPPAS = [F(1), F(5, 4), F(3, 2), F(2), F(3), F(10)]
SEEDS = range(7000, 7600)
TOL = 1e-7


def law_value(z, shares, r, kappa):
    found = asymmetric_zonotope_minimal_cost(z, shares, r, kappa)
    return -np.inf if found["value"] is None else float(np.dot(shares, z)) - found["value"]


def search_law(z, shares, r, kappa, iterations=60):
    """Best kappa-segment law at z, then after a short Nelder-Mead search in z."""
    start = law_value(z, shares, r, kappa)
    free = [i for i in range(len(z)) if 1e-9 < z[i] < 1 - 1e-9]
    if not free:
        return start, start

    def objective(s):
        point = z.copy()
        point[free] = np.clip(s, 0, 1)
        return -law_value(point, shares, r, kappa)

    result = minimize(objective, z[free], method="Nelder-Mead",
                      options={"xatol": 1e-9, "fatol": 1e-11, "maxiter": iterations})
    return start, max(start, -result.fun)


def one(seed):
    rng = random.Random(seed)
    n = rng.choice([4, 4, 5, 5, 6])
    raw = [rng.randint(1, 25) for _ in range(n)]
    shares = [F(x, sum(raw)) for x in raw]
    r = F(rng.randint(1, 49), 50)
    depth = rng.randint(1, n - 3)
    kappa = rng.choice(KAPPAS)
    block = asymmetric_best_block(shares, r, depth, kappa)
    check = verify_segments(block["segments"], shares, r, kappa, block["membership"], block["value"])
    valid = all(v >= 0 for v in check.values()) and check["witness"] == 0
    floats = [float(x) for x in shares]
    bound, z = certificate_bound(floats, float(r), depth, kappa=float(kappa))
    bound = float(bound)
    row = {"seed": seed, "n": n, "depth": depth, "r": str(r), "kappa": str(kappa),
           "shares": [str(x) for x in shares], "block_regime": block["regime"],
           "block_units": len(block["units"]), "block_value": str(block["value"]),
           "block_float": float(block["value"]), "block_valid": valid,
           "certificate": bound, "block_pinned": bool(abs(bound - float(block["value"])) < TOL)}
    if kappa == 1:
        row["symmetric_four_families"] = float(best_general_construction(shares, r, depth)["value"])
        row["symmetric_pinned"] = bool(abs(bound - row["symmetric_four_families"]) < TOL)
    if not row["block_pinned"]:
        cost, _ = minimal_cost(z, floats, float(r), kappa=float(kappa))
        row["relaxation_at_maximizer"] = float(np.dot(floats, z)) - cost
        row["membership"] = [round(float(x), 6) for x in z]
        if n <= 5:
            at_z, searched = search_law(np.asarray(z, dtype=float), floats, float(r), float(kappa))
            row["law_at_maximizer"], row["best_law_found"] = float(at_z), float(searched)
            row["law_pinned"] = bool(abs(bound - searched) < 1e-6)
    return row


def law_cell(row):
    if row.get("symmetric_pinned"):
        return f"{row['symmetric_four_families']:.6f} (transitional family)"
    law = row.get("best_law_found")
    return "not attempted (n = 6)" if law is None else f"{law:.6f}"


def summary(data):
    rows = data["instances"]
    lines = ["# Two-block families for arbitrary shares and asymmetric penalties", "",
             f"{data['date']}. Generated by `scripts/check_asymmetric_general.py` from "
             "[general_shares.json](general_shares.json); theory in "
             "[docs/asymmetric_penalties.md](../../docs/asymmetric_penalties.md), Section 7.", "",
             f"{len(rows)} random instances: n in {{4, 5, 6}}, shares k/sum with k in 1..25, "
             "r = k/50, intermediate depths 1 <= k <= n-3, kappa drawn from "
             f"{{{', '.join(str(k) for k in KAPPAS)}}}. Every two-block law is verified in exact "
             f"arithmetic: {sum(r['block_valid'] for r in rows)} of {len(rows)} valid.", "",
             "For kappa = 1 an explicit law reaching the certificate may also be the fourth (transitional) "
             "family of Conjecture 6.", "",
             "| kappa | instances | two-block value = certificate | otherwise: explicit law reaches it | "
             "otherwise: open | largest open difference |",
             "| --- | ---: | ---: | ---: | ---: | ---: |"]
    for kappa in data["kappas"]:
        group = [r for r in rows if r["kappa"] == kappa]
        if not group:
            continue
        rest = [r for r in group if not r["block_pinned"]]
        reached = [r for r in rest if r.get("law_pinned") or r.get("symmetric_pinned")]
        open_rows = [r for r in rest if not (r.get("law_pinned") or r.get("symmetric_pinned"))]
        largest = max((r["certificate"] - r.get("best_law_found", r["block_float"]) for r in open_rows),
                      default=0.0)
        lines.append(f"| {kappa} | {len(group)} | {len(group) - len(rest)} | {len(reached)} | "
                     f"{len(open_rows)} | {largest:.1e} |")
    sym = [r for r in rows if "symmetric_pinned" in r]
    lines += ["", f"With kappa = 1 the four symmetric families of Conjecture 6 equal the certificate in "
              f"{sum(r['symmetric_pinned'] for r in sym)} of {len(sym)} instances.", "",
              "## Instances where the two-block value is below the certificate", "",
              "| seed | n | depth | r | kappa | two-block | certificate | relaxation at maximizer | "
              "best law found |", "| --- | ---: | ---: | ---: | --- | ---: | ---: | ---: | ---: |"]
    for r in rows:
        if r["block_pinned"]:
            continue
        law = r.get("best_law_found")
        lines.append(f"| {r['seed']} | {r['n']} | {r['depth']} | {r['r']} | {r['kappa']} | "
                     f"{r['block_float']:.6f} | {r['certificate']:.6f} | "
                     f"{r['relaxation_at_maximizer']:.6f} | "
                     f"{law_cell(r)} |")
    lines.append("")
    return "\n".join(lines)


def main():
    start = time.time()
    with ProcessPoolExecutor(max_workers=4) as pool:
        rows = list(pool.map(one, SEEDS))
    data = {"date": "2026-11-07", "kappas": [str(k) for k in KAPPAS], "instances": rows,
            "seconds": round(time.time() - start, 1)}
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "general_shares.json").write_text(
        json.dumps(data, separators=(",", ":"), default=lambda o: o.item()) + "\n")
    saved = json.loads((OUT / "general_shares.json").read_text())
    (OUT / "general_shares.md").write_text(summary(saved))
    invalid = [r for r in saved["instances"] if not r["block_valid"]]
    above = [r for r in saved["instances"] if r["block_float"] > r["certificate"] + 1e-9]
    print(f"done in {data['seconds']} s; invalid laws {len(invalid)}; values above the bound {len(above)}")
    return invalid or above


if __name__ == "__main__":
    import sys
    if "--summary-only" in sys.argv:
        (OUT / "general_shares.md").write_text(
            summary(json.loads((OUT / "general_shares.json").read_text())))
        raise SystemExit(0)
    raise SystemExit(1 if main() else 0)

"""Map of the remaining cases of Conjecture 6 for three free producers.

For random four-producer instances at depth one, every ordering (u, b, c) of
the face {0, 1, 2} is classified by the regions of the proof in
docs/exact_envelopes.md ("Toward a proof of Conjecture 6"): top producer
large (a_u(1+r) >= (1-r)(a_b+a_c), proved), or small with the signs of D and
lambda_L of the transitional certificate. For each ordering the certificate
LP value is compared with the best family value on the face (exact), the
active certificates are recorded, and in the transitional region it is
checked whether the transitional law is valid. Outcomes go to
results/exclusion/three_producers.json; the summary is generated from it.
"""
import json
from pathlib import Path
import collections
import itertools
import random

import numpy as np
from fractions import Fraction as F

from censored_newsvendor.exact_envelopes import (general_cap_binding_candidates,
                                                 general_transitional_candidates)


def families_on_face(shares, r, face):
    """Max family value restricted to one face (excluded = the rest), exact."""
    n = len(shares)
    best = 0
    excluded = tuple(j for j in range(n) if j not in face)
    for c in general_transitional_candidates(shares, r, 1) + general_cap_binding_candidates(shares, r, 1):
        if tuple(c["excluded"]) == excluded:
            best = max(best, c["value"])
    # C31 and H two-block values on this face
    a = [F(x) for x in shares]
    T = sum(a[j] for j in face)
    for size in (1, 2):
        for I in itertools.combinations(face, size):
            aI = sum(a[i] for i in I); AJ = T - aI
            if AJ * (1 - r) / (1 + r) <= aI <= AJ * (1 - r) / (2 * r):
                best = max(best, (1 - r) * T)
            if aI >= AJ * (1 - r) / (2 * r):
                best = max(best, AJ * (1 - r * r) / (2 * r))
    return best



ROOT = Path(__file__).resolve().parents[1]


def analytic_region(a_u, a_b, a_c, r):
    """Proved regions of Proposition T (docs/exact_envelopes.md), for the ordering u, b, c."""
    if a_u * (1 + r) >= (1 - r) * (a_b + a_c):
        return "top producer not small"
    x = (a_u + a_b) / a_c
    if x <= (1 - r) / (1 + r):
        return "{u,b} unit-cap"
    if x <= (1 - r) / (2 * r):
        return "{u,b} ceiling"
    if a_c * (1 - r) >= 2 * a_u:
        return "{u,b} H, a_c(1-r) >= 2a_u"
    return "open"


def main(count=400, seed=3):
    import importlib.util
    spec = importlib.util.spec_from_file_location("ac", ROOT / "scripts/active_certificates.py")
    ac = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(ac)
    rng = random.Random(seed)
    rows = []
    for _ in range(count):
        raw = [rng.randint(1, 30) for _ in range(4)]
        shares = [F(x, sum(raw)) for x in raw]
        r = F(rng.randint(1, 49), 50)
        face = [0, 1, 2]
        fam = families_on_face(shares, r, face)
        a = np.array([float(x) for x in shares])
        trans = [c for c in general_transitional_candidates(shares, r, 1) if tuple(c["excluded"]) == (3,)]
        for u in face:
            for order in itertools.permutations([j for j in face if j != u]):
                b, c = order
                au, ab, ac_ = shares[u], shares[b], shares[c]
                v, act = ac.face_lp(a, float(r), face, u, order)
                small = au * (1 + r) < (1 - r) * (ab + ac_)
                D = r * (au + ab + ac_) + au + ab - ac_
                condL = (1 + r) ** 2 * au + (1 - r) ** 2 * ab >= (1 - r * r) * ac_
                row = {"shares": [str(x) for x in shares], "r": str(r), "order": [u, b, c],
                       "lp": v, "family_max": float(fam), "within": bool(v <= float(fam) + 1e-8),
                       "region": "large" if not small else ("small, D>0, L>=0" if D > 0 and condL else
                                                          ("small, D>0, L<0" if D > 0 else "small, D<=0")),
                       "active": [[list(S), t] for S, t in sorted(ac.label(S, t, u, order) for (_, S, t) in act)]}
                if small and D > 0 and condL:
                    t1 = (1 - r) * (au + ab) / D
                    Vf = au * (1 + r) - ab * (1 - r) + 2 * t1 * ab
                    row["V_formula"] = float(Vf)
                    row["V_law_valid"] = any(c_["units"] == (u,) and c_["transitional"] == b for c_ in trans)
                row["analytic_region"] = analytic_region(au, ab, ac_, r)
                rows.append(row)
    out = ROOT / "results/exclusion"
    (out / "three_producers.json").write_text(json.dumps({"date": "2026-11-07", "rows": rows}) + "\n")
    saved = json.loads((out / "three_producers.json").read_text())["rows"]
    lines = ["# Conjecture 6 for three free producers: map of the cases", "",
             "2026-11-07. Generated by `scripts/three_producers.py` from "
             "[three_producers.json](three_producers.json). Every ordering of the face of "
             f"{len(saved) // 6} random four-producer instances at depth one.", "",
             f"Orderings whose certificate LP value exceeds the best family value on the face: "
             f"{sum(not r['within'] for r in saved)} of {len(saved)}.", "",
             "| region | orderings | status |", "| --- | ---: | --- |"]
    status = {"large": "proved: (1-r)T and H_u bound it, and they equal the two-block value",
              "small, D>0, L>=0": "transitional certificate valid; tight when the transitional law is valid",
              "small, D>0, L<0": "open: other certificate patterns",
              "small, D<=0": "open: other certificate patterns"}
    for region in status:
        group = [r for r in saved if r["region"] == region]
        lines.append(f"| {region} | {len(group)} | {status[region]} |")
    covered = 0
    for row in saved:
        a_u, a_b, a_c = (F(row["shares"][i]) for i in row["order"])
        rr = F(row["r"])
        T, aI = a_u + a_b + a_c, a_u + a_b
        bounds = [(1 - rr) * T, (a_b + a_c) * (1 - rr * rr) / (2 * rr),
                  aI * (1 + rr) * T / (rr * a_c + (1 + rr) * aI)]
        if a_c * (1 - rr) >= 2 * a_u:
            bounds.append(a_c * (1 - rr * rr) / (2 * rr))
        D = rr * T + a_u + a_b - a_c
        if (a_u * (1 + rr) <= (1 - rr) * (a_b + a_c) and D > 0
                and (1 + rr) ** 2 * a_u + (1 - rr) ** 2 * a_b >= (1 - rr * rr) * a_c):
            bounds.append(a_u * (1 + rr) - a_b * (1 - rr) + 2 * (1 - rr) * (a_u + a_b) / D * a_b)
        row["explicit_bound"] = float(min(bounds))
        row["covered"] = bool(row["explicit_bound"] <= row["family_max"] + 1e-9)
        covered += row["covered"]
    lines += ["", f"Five explicit combinations of certificates (ceiling, H_u, G for {{u,b}}, H for {{u,b}} "
              f"when a_c(1-r) >= 2a_u, and the transitional one under its sign conditions) give a bound at or "
              f"below the best family value in {covered} of {len(saved)} orderings. In the others the conjecture "
              "still holds (the LP is below the best family), but further combinations would be needed."]
    lines += ["", "## Analytic regions (Proposition T)", "",
              "| region | orderings | settled by the five bounds |", "| --- | ---: | ---: |"]
    for region in ("top producer not small", "{u,b} unit-cap", "{u,b} ceiling",
                   "{u,b} H, a_c(1-r) >= 2a_u", "open"):
        group = [r for r in saved if r["analytic_region"] == region]
        lines.append(f"| {region} | {len(group)} | {sum(r['covered'] for r in group)} |")
    trans = [r for r in saved if "V_law_valid" in r]
    tight = sum(1 for r in trans if r["V_law_valid"] and abs(r["lp"] - r["V_formula"]) < 1e-8)
    lines += ["", f"In the transitional region the law is valid and attains the certificate value in {tight} "
              f"of {len(trans)} orderings; in the others the value is lower and other patterns are active.", "",
              "## Active certificates by region (most frequent)", "",
              "| region | pattern (S as ranks, rank giving nu) | count |", "| --- | --- | ---: |"]
    for region in status:
        counter = collections.Counter(json.dumps(r["active"]) for r in saved if r["region"] == region)
        for pattern, k in counter.most_common(4):
            lines.append(f"| {region} | {pattern} | {k} |")
    lines.append("")
    (out / "three_producers.md").write_text("\n".join(lines))


if __name__ == "__main__":
    main()
